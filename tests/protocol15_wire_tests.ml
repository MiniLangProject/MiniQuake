function assertEqual(actual, expected, name)
  if actual != expected then return error(9300, name + ": expected " + expected + ", got " + actual) end if
  return true
end function

function assertTrue(value, name)
  if value != true then return error(9301, name + ": expected true") end if
  return true
end function

function assertHex(data, expected, name)
  return assertEqual(hex(data), expected, name)
end function

function runTest(number, name, fn)
  print "  [" + number + "/15] " + name
  result = try(fn())
  if result is error then
    print "    FAIL: " + result.message
    return false
  end if
  return true
end function

