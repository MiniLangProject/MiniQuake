function testPrimitiveStream()
  buffer = sz.alloc(256)
  msg.writeChar(buffer, -2)
  msg.writeByte(buffer, 254)
  msg.writeShort(buffer, -1234)
  msg.writeLong(buffer, 0x12345678)
  msg.writeFloat(buffer, 12.5)
  msg.writeString(buffer, "quake")
  msg.writeCoord(buffer, -12.25)
  msg.writeAngle(buffer, 90.75)
  assertHex(sz.dataSlice(buffer), "fefe2efb78563412000048417175616b65009eff40", "primitive_stream")
  return true
end function

function testReleaseWrapping()
  buffer = sz.alloc(64)
  msg.writeChar(buffer, 130)
  msg.writeByte(buffer, -1)
  msg.writeShort(buffer, 0x12345)
  msg.writeLong(buffer, -2)
  assertHex(sz.dataSlice(buffer), "82ff4523feffffff", "release_wrapping")
  reader = msg.beginReading(buffer)
  assertEqual(msg.readChar(reader), -126, "wrapped MSG_ReadChar")
  assertEqual(msg.readByte(reader), 255, "wrapped MSG_ReadByte")
  assertEqual(msg.readShort(reader), 0x2345, "wrapped MSG_ReadShort")
  assertEqual(msg.readLong(reader), -2, "negative MSG_ReadLong")

  booleanBuffer = sz.alloc(2)
  msg.writeByte(booleanBuffer, false)
  msg.writeByte(booleanBuffer, true)
  assertHex(sz.dataSlice(booleanBuffer), "0001", "qboolean integer ABI")
  return true
end function

function testCoordAngleBoundaries()
  buffer = sz.alloc(128)
  msg.writeCoord(buffer, -0.124)
  msg.writeCoord(buffer, -0.126)
  msg.writeCoord(buffer, 4095.875)
  msg.writeCoord(buffer, 4096.0)
  msg.writeAngle(buffer, -1.9)
  msg.writeAngle(buffer, -90.9)
  msg.writeAngle(buffer, 359.9)
  msg.writeAngle(buffer, 360.0)
  assertHex(sz.dataSlice(buffer), "0000ffffff7f008000c0ff00", "coord_angle_boundaries")

  coordReader = msg.beginReadingBytes(fromHex("0080ff7f"))
  assertEqual(msg.readCoord(coordReader), -4096.0, "signed minimum coord")
  assertEqual(msg.readCoord(coordReader), 4095.875, "signed maximum coord")

  angleReader = msg.beginReadingBytes(bytes([0xff, 0xc0, 0x7f, 0]))
  assertEqual(msg.readAngle(angleReader), -1.40625, "signed 0xff angle")
  assertEqual(msg.readAngle(angleReader), -90.0, "signed 0xc0 angle")
  assertEqual(msg.readAngle(angleReader), 178.59375, "signed 0x7f angle")
  assertEqual(msg.readAngle(angleReader), 0.0, "zero angle")
  return true
end function

function testFloatParameterRounding()
  buffer = sz.alloc(64)
  msg.writeFloat(buffer, 16777217)
  msg.writeCoord(buffer, 0.124999999)
  msg.writeCoord(buffer, -0.124999999)
  msg.writeCoord(buffer, 1.99999999)
  msg.writeCoord(buffer, -1.99999999)
  msg.writeAngle(buffer, 1.99999999)
  msg.writeAngle(buffer, -1.99999999)
  // An integral MiniLang caller still crosses the C float parameter boundary.
  msg.writeCoord(buffer, 16777217)
  assertHex(sz.dataSlice(buffer), "0000804b0100ffff1000f0ff01ff0000", "float_parameter_rounding")
  return true
end function

function testHighBitCString()
  raw = bytes([0x41, 0x80, 0xe9, 0xfe])
  text = protocolText.decodeBytes(raw)
  assertHex(protocolText.encodeBytes(text), "4180e9fe", "high-bit text adapter")

  buffer = sz.alloc(64)
  msg.writeString(buffer, text)
  assertHex(sz.dataSlice(buffer), "4180e9fe00", "raw_high_bit_string")

  reader = msg.beginReading(buffer)
  decoded = msg.readString(reader)
  assertHex(protocolText.encodeBytes(decoded), "4180e9fe", "high-bit wire roundtrip")
  assertEqual(reader.readCount, 5, "high-bit read count")
  return true
end function

function testCStringTerminationAndValidation()
  embedded = decode(bytes([0x41, 0x00, 0x42]))
  buffer = sz.alloc(32)
  msg.writeString(buffer, embedded)
  assertHex(sz.dataSlice(buffer), "4100", "embedded_nul_string")

  nullBuffer = sz.alloc(8)
  msg.writeString(nullBuffer, void)
  assertHex(sz.dataSlice(nullBuffer), "00", "null_string")

  stringOverflow = sz.allocOverflowing(5)
  sz.writeBytes(stringOverflow, bytes([9, 9, 9]))
  msg.writeString(stringOverflow, "xy")
  assertHex(sz.dataSlice(stringOverflow), "787900", "string_overflow_restart")
  assertEqual(stringOverflow.overflowed, true, "string overflow flag")

  outsideLatin1 = decode(bytes([0xe2, 0x82, 0xac]))
  rejected = try(protocolText.encodeBytes(outsideLatin1))
  assertTrue(rejected is error, "non-Latin-1 text rejected")

  rawBuffer = sz.alloc(16)
  msg.writeStringBytes(rawBuffer, bytes([0x51, 0x80, 0, 0x52]))
  assertHex(sz.dataSlice(rawBuffer), "518000", "raw string writer stops at NUL")
  rawReader = msg.beginReading(rawBuffer)
  raw = msg.readStringBytes(rawReader)
  assertHex(raw, "5180", "raw string reader")
  return true
end function

function testSizeBufferPrintAndOverflow()
  // Seed a valid empty C string before exercising the original trailing-NUL
  // replacement path. common.c itself is undefined when cursize == 0.
  printable = sz.alloc(64)
  sz.writeBytes(printable, bytes([0]))
  sz.printText(printable, "one")
  sz.printText(printable, "two")
  assertHex(sz.dataSlice(printable), "6f6e6574776f00", "sz_print_concat")

  safeEmpty = sz.alloc(16)
  sz.printText(safeEmpty, "one")
  assertHex(sz.dataSlice(safeEmpty), "6f6e6500", "safe empty SZ_Print divergence")

  high = protocolText.decodeBytes(bytes([0x80, 0xe9]))
  highPrint = sz.alloc(16)
  sz.printText(highPrint, high)
  assertHex(sz.dataSlice(highPrint), "80e900", "SZ_Print high-bit bytes")

  printOverflow = sz.allocOverflowing(5)
  sz.writeBytes(printOverflow, bytes([7, 7, 7]))
  sz.printText(printOverflow, "ab")
  assertHex(sz.dataSlice(printOverflow), "616200", "sz_print_overflow_restart")
  assertEqual(printOverflow.overflowed, true, "SZ_Print overflow flag")

  safeTrailingOverflow = sz.allocOverflowing(4)
  sz.printText(safeTrailingOverflow, "x")
  sz.printText(safeTrailingOverflow, "abc")
  assertHex(sz.dataSlice(safeTrailingOverflow), "61626300", "safe trailing-NUL overflow restart")
  assertEqual(safeTrailingOverflow.overflowed, true, "safe trailing overflow flag")

  overflowing = sz.allocOverflowing(4)
  sz.writeBytes(overflowing, bytes([1, 2, 3, 4]))
  sz.writeBytes(overflowing, bytes([9, 8]))
  assertHex(sz.dataSlice(overflowing), "0908", "sz_overflow_restart")
  assertEqual(overflowing.curSize, 2, "overflow restart size")
  assertEqual(overflowing.overflowed, true, "overflow flag")
  return true
end function

function testPrimitiveReadsAndBounds()
  data = fromHex("fefe2efb78563412000048417175616b65009eff40")
  reader = msg.beginReadingBytes(data)
  assertEqual(msg.readChar(reader), -2, "MSG_ReadChar")
  assertEqual(msg.readByte(reader), 254, "MSG_ReadByte")
  assertEqual(msg.readShort(reader), -1234, "MSG_ReadShort")
  assertEqual(msg.readLong(reader), 0x12345678, "MSG_ReadLong")
  assertEqual(msg.readFloat(reader), 12.5, "MSG_ReadFloat")
  assertEqual(msg.readString(reader), "quake", "MSG_ReadString")
  assertEqual(msg.readCoord(reader), -12.25, "MSG_ReadCoord")
  assertEqual(msg.readAngle(reader), 90.0, "MSG_ReadAngle quantized")
  assertEqual(msg.remaining(reader), 0, "primitive reader exhausted")

  shortReader = msg.beginReadingBytes(bytes([1]))
  assertEqual(msg.readShort(shortReader), -1, "short overflow sentinel")
  assertEqual(shortReader.badRead, true, "short badRead")
  assertEqual(shortReader.readCount, 0, "short overflow does not advance")

  floatReader = msg.beginReadingBytes(bytes([1, 2, 3]))
  assertEqual(msg.readFloat(floatReader), -1.0, "safe float overflow sentinel")
  assertEqual(floatReader.badRead, true, "safe float badRead")
  assertEqual(floatReader.readCount, 0, "safe float overflow does not advance")
  return true
end function

function testReadStringSignedFF()
  reader = msg.beginReadingBytes(bytes([0x41, 0xff, 0x42, 0]))
  assertEqual(msg.readString(reader), "A", "signed 0xff string terminator")
  assertEqual(reader.readCount, 2, "0xff terminator consumed")
  assertEqual(reader.badRead, false, "0xff is not an overread")
  assertEqual(msg.remaining(reader), 2, "0xff leaves suffix unread")
  return true
end function

function testReadStringStaticLimit()
  data = bytes(2050)
  index = 0
  while index < 2049
    data[index] = 0x61
    index = index + 1
  end while
  reader = msg.beginReadingBytes(data)
  result = msg.readString(reader)
  assertEqual(len(protocolText.encodeBytes(result)), 2047, "MSG_ReadString static payload limit")
  assertEqual(reader.readCount, 2047, "static limit read count")
  assertEqual(msg.remaining(reader), 3, "static limit leaves suffix")
  assertEqual(reader.badRead, false, "static limit is not badRead")
  return true
end function

