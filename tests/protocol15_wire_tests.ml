function testAllByteTextAdapter()
  raw = bytes(255)
  index = 0
  while index < 255
    raw[index] = index + 1
    index = index + 1
  end while
  text = protocolText.decodeBytes(raw)
  assertHex(protocolText.encodeBytes(text), hex(raw), "all non-NUL Quake bytes reversible")
  assertEqual(protocolText.TEXT_ABI, "quake_latin1_cstring_v1", "protocol text ABI")
  return true
end function

function testSizeBufferExactFitAndErrors()
  exact = sz.alloc(4)
  offset = sz.getSpace(exact, 4)
  assertEqual(offset, 0, "exact fit offset")
  assertEqual(exact.curSize, 4, "exact fit size")
  failure = try(sz.getSpace(exact, 1))
  assertTrue(failure is error, "overflow without permission rejected")
  assertEqual(exact.curSize, 4, "rejected overflow leaves size")

  tooLarge = sz.allocOverflowing(4)
  failure = try(sz.getSpace(tooLarge, 5))
  assertTrue(failure is error, "single request larger than buffer rejected")
  assertEqual(tooLarge.curSize, 0, "oversized request leaves size")
  assertEqual(tooLarge.overflowed, false, "oversized request leaves overflow flag")
  return true
end function


function main(args)
  print "MiniQuake BP-010R1 Protocol 15 wire tests"
  passed = 0
  if runTest("01", "Protocol 15 constants", testProtocolConstants) then passed = passed + 1 end if
  if runTest("02", "primitive MSG stream", testPrimitiveStream) then passed = passed + 1 end if
  if runTest("03", "release integer wrapping", testReleaseWrapping) then passed = passed + 1 end if
  if runTest("04", "coord and angle boundaries", testCoordAngleBoundaries) then passed = passed + 1 end if
  if runTest("05", "C float-parameter rounding", testFloatParameterRounding) then passed = passed + 1 end if
  if runTest("06", "high-bit Quake C strings", testHighBitCString) then passed = passed + 1 end if
  if runTest("07", "C-string termination and validation", testCStringTerminationAndValidation) then passed = passed + 1 end if
  if runTest("08", "SZ_Print and overflow restart", testSizeBufferPrintAndOverflow) then passed = passed + 1 end if
  if runTest("09", "primitive reads and bounds", testPrimitiveReadsAndBounds) then passed = passed + 1 end if
  if runTest("10", "signed 0xff string termination", testReadStringSignedFF) then passed = passed + 1 end if
  if runTest("11", "MSG_ReadString static limit", testReadStringStaticLimit) then passed = passed + 1 end if
  if runTest("12", "CL_SendMove wire image", testClcMoveGolden) then passed = passed + 1 end if
  if runTest("13", "baseline wire image", testBaselineGolden) then passed = passed + 1 end if
  if runTest("14", "all non-NUL Quake bytes", testAllByteTextAdapter) then passed = passed + 1 end if
  if runTest("15", "sizebuf exact fit and errors", testSizeBufferExactFitAndErrors) then passed = passed + 1 end if

  if passed != 15 then
    print "MiniQuake BP-010R1 Protocol 15 wire tests failed: " + passed + "/15"
    return 1
  end if
  print "MiniQuake BP-010R1 Protocol 15 wire tests passed: 15"
  return 0
end function
